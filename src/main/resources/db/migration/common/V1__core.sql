CREATE TABLE setting (
    key VARCHAR(100) PRIMARY KEY,
    value TEXT
);

CREATE TABLE author (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) UNIQUE NOT NULL,
    display_name VARCHAR(250),
    email VARCHAR(100),
    slug VARCHAR(200) UNIQUE NOT NULL,
    source_id BIGINT
);

CREATE TABLE item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT UNIQUE,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    password_protected BOOLEAN NOT NULL DEFAULT FALSE,
    title TEXT,
    slug VARCHAR(200),
    permalink VARCHAR(2000) UNIQUE,
    body TEXT,
    body_format VARCHAR(10) NOT NULL,
    excerpt TEXT,
    author_id BIGINT REFERENCES author (id),
    parent_id BIGINT REFERENCES item (id),
    published_at TIMESTAMP,
    modified_at TIMESTAMP,
    guid VARCHAR(2000),
    comment_status VARCHAR(10),
    menu_order INT DEFAULT 0,
    mime_type VARCHAR(100)
);

CREATE TABLE term (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT,
    taxonomy VARCHAR(32) NOT NULL,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL,
    parent_id BIGINT REFERENCES term (id),
    description TEXT,
    UNIQUE (taxonomy, slug)
);

CREATE TABLE item_term (
    item_id BIGINT REFERENCES item (id),
    term_id BIGINT REFERENCES term (id),
    PRIMARY KEY (item_id, term_id)
);

CREATE TABLE reusable_block (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT UNIQUE,
    title TEXT,
    content TEXT NOT NULL
);

CREATE TABLE comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT UNIQUE,
    item_id BIGINT NOT NULL REFERENCES item (id),
    parent_id BIGINT REFERENCES comment (id),
    author_name VARCHAR(250),
    author_email VARCHAR(100),
    author_url VARCHAR(200),
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT REFERENCES item (id),
    source_url VARCHAR(2000) UNIQUE NOT NULL,
    path VARCHAR(1000),
    mime_type VARCHAR(100),
    sha256 VARCHAR(64)
);

CREATE TABLE redirect (
    from_path VARCHAR(2000) PRIMARY KEY,
    to_path VARCHAR(2000) NOT NULL,
    status_code INT NOT NULL DEFAULT 301
);
