-- object_type: 'item' or 'block'; autosave rows are not revisions
CREATE TABLE revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_type VARCHAR(20) NOT NULL,
    object_id BIGINT NOT NULL,
    title TEXT,
    body TEXT,
    body_format VARCHAR(10),
    excerpt TEXT,
    author_id BIGINT REFERENCES author (id),
    created_at TIMESTAMP NOT NULL,
    autosave BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX revision_object ON revision (object_type, object_id, created_at);

-- kind: item | base | media | all; ref: the item id or the listing base path
CREATE TABLE publish_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(10) NOT NULL,
    ref VARCHAR(2000),
    queued_at TIMESTAMP NOT NULL
);

CREATE TABLE item_fragment (
    item_id BIGINT PRIMARY KEY REFERENCES item (id),
    html TEXT NOT NULL
);

-- bases: the listing bases the item was published into, one per line
CREATE TABLE published_item (
    item_id BIGINT PRIMARY KEY,
    permalink VARCHAR(2000) NOT NULL,
    bases TEXT NOT NULL
);

