-- db-scheduler's table, portable form
CREATE TABLE scheduled_tasks (
    task_name VARCHAR(100) NOT NULL,
    task_instance VARCHAR(200) NOT NULL,
    task_data BYTEA,
    execution_time TIMESTAMP WITH TIME ZONE NOT NULL,
    picked BOOLEAN NOT NULL,
    picked_by VARCHAR(50),
    last_success TIMESTAMP WITH TIME ZONE,
    last_failure TIMESTAMP WITH TIME ZONE,
    consecutive_failures INT,
    last_heartbeat TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL,
    priority SMALLINT,
    PRIMARY KEY (task_name, task_instance)
);
CREATE INDEX scheduled_tasks_execution_time ON scheduled_tasks (execution_time);
CREATE INDEX scheduled_tasks_last_heartbeat ON scheduled_tasks (last_heartbeat);
CREATE INDEX scheduled_tasks_priority ON scheduled_tasks (priority);
